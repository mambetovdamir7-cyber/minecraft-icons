  const LEVEL_CLASS = { "легко": "lv-easy", "средне": "lv-mid", "сложно": "lv-hard" };

  function renderEnch() {
    const box = $("ench-grid");
    if (!box || box.childElementCount) return;
    ENCH.forEach((e) => {
      const card = document.createElement("article");
      card.className = "guide-card";
      card.innerHTML = `
        <div class="guide-head">
          ${img(e.id, 40)}
          <div>
            <h3>${e.name}</h3>
            <span class="guide-tier">${e.tier}</span>
          </div>
        </div>
        <ul class="ench-list">
          ${e.best.map(([n, l]) => `<li><span>${n}</span><b>${l}</b></li>`).join("")}
        </ul>
        ${e.alt.filter((a) => a[0] !== "—").length ? `<div class="ench-alt">
          <span class="ench-alt-title">Альтернативы</span>
          ${e.alt.filter((a) => a[0] !== "—").map(([n, l, why]) => `<p><b>${n} ${l}</b> — ${why}</p>`).join("")}
        </div>` : ""}
        <p class="guide-note">${e.note}</p>
      `;
      box.appendChild(card);
    });
  }

  function renderFarms() {
    const box = $("farms-grid");
    if (!box || box.childElementCount) return;
    FARMS.forEach((f) => {
      const card = document.createElement("article");
      card.className = "guide-card farm";
      card.innerHTML = `
        <div class="guide-head">
          ${img(f.id, 40)}
          <div>
            <h3>${f.name}</h3>
            <span class="farm-level ${LEVEL_CLASS[f.level] || ""}">${f.level}</span>
          </div>
        </div>
        <div class="farm-need">
          <span class="farm-label">Нужно</span>
          <p>${f.need.join(" · ")}</p>
        </div>
        <ol class="farm-steps">
          ${f.how.map((s) => `<li>${s}</li>`).join("")}
        </ol>
        <p class="farm-out"><span class="farm-label">Выход</span> ${f.out}</p>
      `;
      box.appendChild(card);
    });
  }

  window.MCU_GUIDES = { ench: renderEnch, farms: renderFarms };
